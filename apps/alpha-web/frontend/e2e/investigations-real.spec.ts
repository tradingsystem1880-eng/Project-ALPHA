import { expect, test } from '@playwright/test'
import { openTask } from './support/workstationHarness'

// Real browser -> API -> CLI -> persisted cases. Only inference and vendor fetch are test doubles
// installed by the disposable test server, never by production configuration.
test('real persisted investigation supports followup, cancel, refresh and comparison handoff', async ({page, request}) => {
  test.setTimeout(180_000)
  expect((await request.post('/__fixture/investigations')).ok()).toBe(true)
  await page.goto('')
  await openTask(page, 'Results', 'Run library')
  const leaf = page.getByRole('tree', {name: 'Navigator'}).locator('.tree-leaf').filter({hasText: 'run 12345678'})
  await expect(leaf).toBeVisible({timeout: 30_000})
  await leaf.click()
  await page.getByRole('button', {name: 'Investigate this run', exact: true}).click()
  const panel = page.getByRole('region', {name: 'Run investigation'})
  await panel.getByLabel('Investigation question').fill(`Synthetic operational investigation ${test.info().project.name}`)
  await panel.getByRole('button', {name: 'Start new investigation'}).click()
  await expect(panel.getByText(/Synthetic fixture has a concentrated drawdown/)).toBeVisible({timeout: 30_000})
  const id = await panel.getByLabel('Saved investigations').inputValue()
  await panel.getByLabel('Investigation follow-up').fill('pause for cancellation test')
  await panel.getByRole('button', {name: 'Ask follow-up'}).click()
  await expect.poll(async () => (await (await request.get(`/api/investigations/${id}`)).json()).status, {timeout: 30_000}).toBe('running')
  await panel.getByRole('button', {name: 'Cancel investigation'}).click()
  await expect.poll(async () => (await (await request.get(`/api/investigations/${id}`)).json()).status, {timeout: 30_000}).toBe('interrupted')
  await page.reload()
  await openTask(page, 'Results', 'Run library')
  await leaf.click()
  await page.getByRole('button', {name: 'Investigate this run', exact: true}).click()
  await expect(panel.getByRole('button', {name: 'Resume investigation'})).toBeEnabled({timeout: 30_000})
  const stored = await (await request.get(`/api/investigations/${id}`)).json()
  expect(stored.turns_remaining).toBe(2)
  expect(stored.report.limitations[0]).toContain('test doubles')
  await panel.getByText('Acquire comparison evidence', {exact: true}).click()
  await panel.getByRole('button', {name: 'Preview acquisition plan'}).click()
  await panel.getByRole('button', {name: 'Acquire this comparison plan'}).click()
  await expect(panel.getByRole('button', {name: 'Open comparison investigation'})).toBeEnabled({timeout: 30_000})
  await panel.getByRole('button', {name: 'Open comparison investigation'}).click()
  await expect(panel.getByLabel('Saved investigations')).not.toHaveValue(id, {timeout: 30_000})
  await expect(panel.getByRole('button', {name: 'Resume investigation'})).toBeEnabled({timeout: 30_000})
  const childId = await panel.getByLabel('Saved investigations').inputValue()
  expect(childId).not.toBe(id)
  const child = await (await request.get(`/api/investigations/${childId}`)).json()
  expect(child.parent_id).toBe(id)
  expect(child.authority).toBe('none')
  expect(child.turns_remaining).toBe(4)
  expect((await (await request.get(`/api/investigations/${id}`)).json()).turns_remaining).toBe(2)
})
