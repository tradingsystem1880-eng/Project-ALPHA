"""Internal injected response reader; no live opener, retry or acquisition route."""

from __future__ import annotations

import math
from asyncio import CancelledError
from collections.abc import Callable, Mapping
from typing import Protocol
from urllib.error import HTTPError
from urllib.request import Request

from alpha_core import DataError

from .bybit import bybit_public_url


class FundingResponse(Protocol):
    @property
    def headers(self) -> Mapping[str, str]: ...
    def getcode(self) -> int: ...
    def geturl(self) -> str: ...
    def read(self, size: int) -> bytes: ...
    def close(self) -> None: ...


type ResponseOpener = Callable[[Request, float], FundingResponse]


class _ResponseFailure(Exception):
    """Only static messages generated by this module may escape sanitization."""


_CANCELLATIONS = (KeyboardInterrupt, SystemExit, GeneratorExit, CancelledError)


def _safe_cancellation(error: BaseException) -> BaseException:
    if isinstance(error, SystemExit):
        code = error.code
        return SystemExit(
            0 if code is None else code if type(code) is int and 0 <= code <= 255 else 1
        )
    if isinstance(error, KeyboardInterrupt):
        return KeyboardInterrupt()
    if isinstance(error, GeneratorExit):
        return GeneratorExit()
    return CancelledError()


class FundingResponseSupplier:
    """PageSupplier with mandatory opener/clock injection and one shared deadline.

    The opener must refuse redirects before following and honor its I/O timeout.
    This adapter verifies final URL/status but cannot undo a redirect or preempt
    arbitrary open/read/close code. urllib-style timeout applies to blocking I/O,
    not total elapsed time; aggregate deadline is checked between operations.
    """

    def __init__(
        self,
        open_response: ResponseOpener,
        *,
        clock: Callable[[], float],
        timeout_seconds: float = 10,
        total_seconds: float = 30,
    ) -> None:
        for value, ceiling in ((timeout_seconds, 60), (total_seconds, 300)):
            if (
                type(value) not in {float, int}
                or not math.isfinite(value)
                or not 0 < value <= ceiling
            ):
                raise DataError("bounded response timeout/deadline is invalid")
        first: float | None = None
        clock_failure: BaseException | None = None
        try:
            first = clock()
        except BaseException as exc:
            clock_failure = exc
            first = None  # Normalize a failed clock without retaining exception text/context.
        if isinstance(clock_failure, _CANCELLATIONS):
            cancellation = _safe_cancellation(clock_failure)
            clock_failure = None
            raise cancellation from None
        clock_failure = None
        if type(first) not in {float, int} or first is None or not math.isfinite(first):
            raise DataError("bounded response clock is invalid")
        self._open = open_response
        self._clock = clock
        self._last = first
        self._deadline = first + total_seconds
        self._timeout = timeout_seconds

    def _remaining(self) -> float:
        now = self._clock()
        if type(now) not in {float, int} or not math.isfinite(now) or now < self._last:
            raise _ResponseFailure("bounded response clock is invalid")
        self._last = now
        remaining = self._deadline - now
        if remaining <= 0:
            raise _ResponseFailure("bounded response deadline expired")
        return remaining

    def __call__(self, params: dict[str, str | int], allowance: int) -> bytes:
        if type(allowance) is not int or not 1 <= allowance <= 8 * 1024 * 1024:
            raise DataError("bounded response byte allowance is invalid")
        response: FundingResponse | None = None
        failure: BaseException | None = None
        payload = b""
        try:
            self._remaining()
            expected_url = bybit_public_url("funding", params)
            request = Request(
                expected_url,
                headers={
                    "Accept": "application/json",
                    "Accept-Encoding": "identity",
                    "User-Agent": "Project-ALPHA/1.0",
                },
            )
            response = self._open(request, min(self._timeout, self._remaining()))
            self._remaining()
            if (
                response.getcode() != 200
                or request.full_url != expected_url
                or response.geturl() != expected_url
            ):
                raise _ResponseFailure("bounded response status or redirect is invalid")
            headers: dict[str, str] = {}
            for key, value in response.headers.items():
                name = key.lower()
                if name in headers:
                    raise _ResponseFailure("bounded response duplicate header is invalid")
                headers[name] = value
            if headers.get("content-type", "").split(";", 1)[0].strip().lower() not in {
                "application/json",
                "text/json",
            }:
                raise _ResponseFailure("bounded response MIME is invalid")
            if headers.get("content-encoding", "identity").strip().lower() != "identity":
                raise _ResponseFailure("bounded response encoding is invalid")
            declared = headers.get("content-length")
            length: int | None = None
            if declared is not None:
                if not declared.isascii() or not declared.isdecimal() or len(declared) > 10:
                    raise _ResponseFailure("bounded response length is invalid")
                length = int(declared)
                if length > allowance:
                    raise _ResponseFailure("bounded response declared byte limit exceeded")
            chunks: list[bytes] = []
            size = 0
            while True:
                self._remaining()
                requested = min(65536, allowance - size + 1)
                chunk = response.read(requested)
                self._remaining()
                if type(chunk) is not bytes or len(chunk) > requested:
                    raise _ResponseFailure("bounded response read contract is invalid")
                size += len(chunk)
                if size > allowance:
                    raise _ResponseFailure("bounded response byte limit exceeded")
                if not chunk:
                    break
                chunks.append(chunk)
            if length is not None and size != length:
                raise _ResponseFailure("bounded response length differs from body")
            payload = b"".join(chunks)
        except BaseException as exc:
            failure = exc
            # urllib HTTPError can own a response even when open never returns one.
            if response is None and isinstance(exc, HTTPError):
                try:
                    exc.close()
                except BaseException as cleanup:
                    failure = (
                        cleanup
                        if isinstance(cleanup, _CANCELLATIONS)
                        else _ResponseFailure("bounded response open/cleanup failed")
                    )
        finally:
            if response is not None:
                try:
                    response.close()
                except BaseException as exc:
                    if failure is None or isinstance(exc, _CANCELLATIONS):
                        failure = exc
        if failure is None:
            try:
                self._remaining()
            except BaseException as exc:
                failure = exc
        # Raise outside the original handler: no URL-bearing exception context/cause.
        if isinstance(failure, _CANCELLATIONS):
            cancellation = _safe_cancellation(failure)
            failure = None
            raise cancellation from None
        if failure is not None:
            message = (
                str(failure)
                if type(failure) is _ResponseFailure
                else "bounded response transport failed"
            )
            failure = None
            raise DataError(message) from None
        return payload
